/*
 * Докъде е стигнала програмата: пази се в backup SRAM при спиране на тока.
 * Copyright (c) 2026 ageorgiev86. Всички права запазени.
 *
 * Linux праща PROG_POS (docs/spi-protokol.md, раздел 6.1) при смяна на реда.
 * STM32 го записва в backup SRAM (4 KB на 0x38800000). Тя се пази и без
 * захранване, ако на пина VBAT на конектора U10 има батерия CR2032 (по
 * схемата VBAT на чипа е през диод BAT54C от 3,3 V и от този пин).
 *
 * Записът е в две копия, които се редуват, всяко с пореден номер и CRC-32.
 * Ако токът спре по време на запис, остава предишното копие. MPU прави
 * паметта некеширана (main.c), за да стига записът веднага до нея.
 */
#ifndef RESUME_H
#define RESUME_H

#include <stdint.h>

/* съдържанието на PROG_POS (16 байта, както в протокола) */
struct prog_pos {
  uint32_t file_crc;    /* CRC-32 на файла с програмата */
  uint32_t line;        /* ред; 0 = няма прекъсната програма (потвърждение или нова) */
  uint32_t part;        /* детайл (0 = G54, 1… = отметнатите G55–G59 подред) */
  uint32_t segment;     /* номер на сегмента на движението */
};

/* Вика се веднъж при старт: включва backup SRAM и прочита записа отпреди. */
void resume_init(void);

/* Записва новата позиция (от PROG_POS). Ред 0 изчиства прекъсването. */
void resume_store(const struct prog_pos *p);

/*
 * Какво е намерено при старта (за RESUME_INFO). Връща 1, ако има прекъсната
 * програма (валиден запис с ред ≠ 0), и я копира в *p. След resume_store
 * с ред 0 връща 0.
 */
int resume_boot_info(struct prog_pos *p);

/* 1, ако backup регулаторът е готов (има VBAT): записът оцелява без ток. */
int resume_battery_ok(void);

/* CRC-32 като в zlib и в протокола (полином 0xEDB88320, обърнат). */
uint32_t crc32_calc(uint32_t crc, const void *data, uint32_t len);

#endif /* RESUME_H */
